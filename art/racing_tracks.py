"""Build public/games/racing/tracks.js from real track layouts.

Sources (both from the Formula Electric at Berkeley GitHub org):
  - FEBSim (Formula-Electric-Berkeley/FEBSim): custom-sim/track_files/Michigan_2021_Endurance.csv
  - FEBSim (FormulaElectricBerkeley/FEBSim, OpenLap fork): OpenLap/<circuit>.xlsx, from OpenLAP by
    Michael Chalkiopoulos (GPL-3.0). Circuits are scaled down so a lap suits an FSAE car.

Each layout is a list of straights and constant-radius arcs. Arc angles are rescaled so the lap turns
exactly 360 degrees (the measured files are a few degrees off); the remaining position gap is closed in
the game when it builds the centreline. The longest straight is rotated to the front so the start line
lands on it.

Usage:
  python3 art/racing_tracks.py <FEBSim checkout> <OpenLap checkout dir>        # writes tracks.js
  python3 art/racing_tracks.py <FEBSim checkout> <OpenLap checkout dir> --check  # clearance report only

Standard library only.
"""
import csv, json, math, os, re, sys, zipfile
import xml.etree.ElementTree as ET

OUT = os.path.join(os.path.dirname(__file__), '..', 'public', 'games', 'racing', 'tracks.js')
