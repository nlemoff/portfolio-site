NS = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'

# id: (title, subtitle, source, scale, half width m, elevation mode)
TRACKS = {
    'michigan': ('Michigan', 'FSAE endurance 2021', ('csv', 'custom-sim/track_files/Michigan_2021_Endurance.csv'), 1.0, 2.5, 'flat'),  # 5 m: FSAE endurance minimum is 4.5 m
    'spa': ('Spa', 'Francorchamps, 0.28 scale', ('xlsx', 'Spa-Francorchamps.xlsx'), 0.28, 4.0, 'data'),
    'monza': ('Monza', 'Autodromo Nazionale, 0.30 scale', ('xlsx', 'Autodromo Nazionale Monza.xlsx'), 0.30, 4.0, 'gentle'),
    'donington': ('Donington', 'Donington Park, 0.45 scale', ('xlsx', 'Donington Park.xlsx'), 0.45, 4.0, 'gentle'),
}


def attr(el, name):
    v = el.get(name)
    if v is None: raise ValueError(f'xlsx: missing {name}')
    return v


def read_xlsx(path):
    z = zipfile.ZipFile(path)
    ss = [''.join(t.text or '' for t in si.iter(NS + 't')) for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall(NS + 'si')] if 'xl/sharedStrings.xml' in z.namelist() else []
    wb = ET.fromstring(z.read('xl/workbook.xml'))
    rels = {r.get('Id'): r.get('Target') for r in ET.fromstring(z.read('xl/_rels/workbook.xml.rels'))}
    out = {}
    sheets = wb.find(NS + 'sheets')
    if sheets is None: raise ValueError('xlsx: no sheets')
    for s in sheets:
        tgt = (rels[attr(s, '{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id')] or '').lstrip('/')
        tgt = tgt if tgt.startswith('xl/') else 'xl/' + tgt
        rows = []
        for r in ET.fromstring(z.read(tgt)).iter(NS + 'row'):
            row = {}
            for c in r.findall(NS + 'c'):
                v = c.find(NS + 'v')
                if v is None: continue
                col = 0
                m = re.match(r'[A-Z]+', attr(c, 'r'))
                for ch in (m.group() if m else 'A'): col = col * 26 + ord(ch) - 64
                text = v.text or ''
                row[col - 1] = ss[int(text)] if c.get('t') == 's' else text
            if row: rows.append([row.get(i, '') for i in range(max(row) + 1)])
        out[s.get('name')] = rows
    return out


def num(x):
    try: return float(x)
    except (TypeError, ValueError): return None


def load(src, febsim, openlap):
    kind, rel = src
    if kind == 'csv':
        rows = list(csv.reader(open(os.path.join(febsim, rel), encoding='utf-8-sig')))[1:]
        return [(r[0], float(r[1]), num(r[2]) or 0.0) for r in rows if r and r[0]], []
    wb = read_xlsx(os.path.join(openlap, rel))
    segs = [(r[0], float(r[1]), (num(r[2]) if len(r) > 2 else None) or 0.0) for r in wb['Shape'][1:] if len(r) > 1 and num(r[1])]
    elev = [(float(r[0]), float(r[1])) for r in wb.get('Elevation', [])[1:] if len(r) > 1 and num(r[0]) is not None and num(r[1]) is not None]
    return segs, elev


def to_game(segs, scale):
    """[('S', len) | ('L'|'R', radius, degrees)] (the game's order), scaled, arcs normalised to a 360-degree lap."""
    out, turn = [], 0.0
    for t, l, r in segs:
        if t.lower().startswith('s') or r <= 0: out.append(['S', l * scale])
        else:
            sg = 1 if t.lower().startswith('l') else -1
            out.append(['L' if sg > 0 else 'R', r * scale, math.degrees(l / r)]); turn += sg * l / r
    k = 2 * math.pi / abs(turn)
    for s in out:
        if s[0] != 'S': s[2] *= k
    # merge consecutive straights, rotate so the longest straight comes first
    merged = []
    for s in out:
        if merged and s[0] == 'S' and merged[-1][0] == 'S': merged[-1][1] += s[1]
        else: merged.append(s)
    if len(merged) > 1 and merged[0][0] == 'S' and merged[-1][0] == 'S':
        merged[0][1] += merged.pop()[1]
    i = max(range(len(merged)), key=lambda j: merged[j][1] if merged[j][0] == 'S' else -1)
    seg_len = lambda s: s[1] if s[0] == 'S' else s[1] * math.radians(s[2])
    start_frac = sum(seg_len(s) for s in merged[:i]) / sum(seg_len(s) for s in merged)
    return merged[i:] + merged[:i], start_frac


def centreline(seg, passes=3):
    """Same construction as the game: turtle at ~1 m spacing, then `passes` of closed smoothing (3 for real layouts)."""
    x = y = h = 0.0; raw = [(0.0, 0.0)]
    for s in seg:
        if s[0] == 'S':
            n = max(1, math.ceil(s[1]))
            for i in range(1, n + 1): raw.append((x + math.cos(h) * s[1] * i / n, y + math.sin(h) * s[1] * i / n))
            x += math.cos(h) * s[1]; y += math.sin(h) * s[1]
        else:
            sg = 1 if s[0] == 'L' else -1; r = s[1]; a = math.radians(s[2]); n = max(2, math.ceil(r * a))
            cx, cy = x - math.sin(h) * r * sg, y + math.cos(h) * r * sg
            for i in range(1, n + 1):
                hh = h + sg * a * i / n; raw.append((cx + math.sin(hh) * r * sg, cy - math.cos(hh) * r * sg))
            h += sg * a; x, y = raw[-1]
    gx, gy = raw[-1]; raw.pop()
    # close the position gap linearly along the lap (the game does the same)
    n = len(raw); raw = [(p[0] - gx * i / n, p[1] - gy * i / n) for i, p in enumerate(raw)]
    p = raw
    for _ in range(passes):
        m = len(p)
        p = [((p[i - 2][0] + 2 * p[i - 1][0] + 2 * p[i][0] + 2 * p[(i + 1) % m][0] + p[(i + 2) % m][0]) / 8,
              (p[i - 2][1] + 2 * p[i - 1][1] + 2 * p[i][1] + 2 * p[(i + 1) % m][1] + p[(i + 2) % m][1]) / 8) for i in range(m)]
    return p, math.hypot(gx, gy)


def report(tid, seg, half_w):
    p, gap = centreline(seg)
    m = len(p); cum = [0.0]
    for i in range(m): cum.append(cum[-1] + math.dist(p[i], p[(i + 1) % m]))
    L = cum[-1]
    # tightest radius (3-point) and closest approach of two different parts of the lap
    minr, sep = 1e9, 1e9
    for i in range(0, m, 2):
        a, b, c = p[i - 3], p[i], p[(i + 3) % m]
        ab, bc, ca = math.dist(a, b), math.dist(b, c), math.dist(c, a)
        cross = abs((b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]))
        if cross > 1e-9: minr = min(minr, ab * bc * ca / (2 * cross))
    for i in range(0, m, 4):
        for j in range(i + 4, m, 4):
            d = math.dist(p[i], p[j]); arc = min(abs(cum[j] - cum[i]), L - abs(cum[j] - cum[i]))
            if arc > 2.2 * d + 6: sep = min(sep, d)
    print(f'{tid:10s} lap {L:6.0f} m  closure fixed {gap:5.1f} m  segments {len(seg):3d}  tightest r {minr:5.1f} m  '
          f'closest other section {sep:5.1f} m  (needs > {2 * (half_w + 1):.1f})')


def main():
    if len(sys.argv) < 3: sys.exit(__doc__)
    febsim, openlap = sys.argv[1], sys.argv[2]
    data = {}
    for tid, (title, sub, src, scale, half_w, emode) in TRACKS.items():
        segs, elev = load(src, febsim, openlap)
        seg, start_frac = to_game(segs, scale)
        report(tid, seg, half_w)
        entry = {'name': title, 'sub': sub, 'halfW': half_w, 'seg': [[s[0]] + [round(v, 3) for v in s[1:]] for s in seg]}
        if emode == 'data' and elev:
            # elevation vs distance in the original lap, re-based to the rotated start and scaled with the track
            orig_len = sum(l for _, l, _ in segs); lo = min(e for _, e in elev)
            entry['elev'] = [[round((d / orig_len - start_frac) % 1.0, 4), round((e - lo) * scale, 2)] for d, e in elev]
            entry['elev'].sort()
        else:
            entry['elevMode'] = emode
        data[tid] = entry
    if '--check' in sys.argv: return
    with open(OUT, 'w') as f:
        f.write(HEADER)
        f.write('export const TRACKS = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    print('wrote', os.path.relpath(OUT), os.path.getsize(OUT), 'bytes')


if __name__ == '__main__':
    main()
